'use strict';
/**
 * Regression test for PR 7 independent review P1 (packages/development/commands/
 * beads-build-wave.yaml Step 2): a prior refactor inverted the work-graph.plan ->
 * work-graph.ready fallback condition, triggering it on "unavailable, errors, OR returns zero
 * tracks" instead of ONLY on an {ok:false} plan result (UNAVAILABLE/any error). A plan that
 * succeeds with zero tracks is an EMPTY PLAN (handled by Step 3's own "If zero tracks returned:
 * skip to Step 7" empty-plan edge, which the inverted condition made unreachable for the
 * legitimate empty-plan case: it would instead force every genuinely empty plan through
 * work-graph.ready and dispatch one single-bead track per ready item, even though the actual
 * scheduler said there was nothing to schedule).
 *
 * This asserts the specific buggy trigger phrase ("errors, or returns zero tracks") is absent
 * from the SOURCE YAML and from the generated command text every one of the four shipped
 * runtimes actually carries this prose into: claude/markdown (packages/development/commands/
 * ensemble/*.md), pi (packages/pi/prompts/_hidden/*.md), codex (packages/codex/.codex/skills/
 * commands/*\/SKILL.md, all three checked-in and already regenerated by this same fix), and
 * opencode (no static vendored copy -- generated fresh into a throwaway os.tmpdir() output dir
 * via `scripts/generate-opencode/index.js`, exactly like `toolchain-runtime-parity.test.js`
 * does for its own cross-runtime checks).
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const { readSkillProse } = require('../lib/skill-backed-command');

const REPO_ROOT = path.join(__dirname, '..', '..');
// beads-build-wave is skill-backed: its YAML is a manifest, the prompt (source of truth) is its skill
// (SKILL.md + references/). SOURCE_PATH is that skill; the source-text assertions read its prose.
const SOURCE_PATH = path.join(REPO_ROOT, 'packages', 'development', 'skills', 'ensemble-beads-build-wave', 'SKILL.md');
const readSource = () => readSkillProse(SOURCE_PATH);
const CLAUDE_GENERATED_PATH = path.join(
  REPO_ROOT,
  'packages',
  'development',
  'commands',
  'ensemble',
  'beads-build-wave.md'
);
const PI_GENERATED_PATH = path.join(REPO_ROOT, 'packages', 'pi', 'prompts', '_hidden', 'ensemble-beads-build-wave.md');
const CODEX_GENERATED_PATH = path.join(
  REPO_ROOT,
  'packages',
  'codex',
  '.codex',
  'skills',
  'commands',
  'ensemble-beads-build-wave',
  'SKILL.md'
);

// The exact buggy trigger phrase this task removed: a work-graph.plan result that "returns
// zero tracks" must NEVER be grouped with "unavailable"/"errors" as a reason to fall back to
// the required work-graph.ready capability -- that is the inverted condition.
const BUGGY_TRIGGER_PHRASE = /unavailable, errors, or returns zero tracks/;

describe('PR7 independent review P1: beads-build-wave.yaml Step 2 fallback condition is never inverted, in source or in any generated runtime copy', () => {
  test('source YAML does not contain the buggy "unavailable, errors, or returns zero tracks" trigger phrase', () => {
    const contents = readSource();
    expect(contents).not.toMatch(BUGGY_TRIGGER_PHRASE);
    // Sanity: the file still documents the CORRECT condition explicitly, so this isn't merely
    // an accidental rewording that silently dropped the fallback altogether.
    expect(contents).toContain('If the result is {ok:false} (UNAVAILABLE or any other error)');
    expect(contents).toContain("that is an EMPTY PLAN, handled at Step 3's empty-plan edge (Step 7), never a fallback trigger");
  });

  test('claude/markdown generated copy (packages/development/commands/ensemble/beads-build-wave.md) does not contain the buggy phrase', () => {
    const contents = fs.readFileSync(CLAUDE_GENERATED_PATH, 'utf8');
    expect(contents).not.toMatch(BUGGY_TRIGGER_PHRASE);
  });

  test('pi generated copy (packages/pi/prompts/_hidden/ensemble-beads-build-wave.md) does not contain the buggy phrase', () => {
    const contents = fs.readFileSync(PI_GENERATED_PATH, 'utf8');
    expect(contents).not.toMatch(BUGGY_TRIGGER_PHRASE);
  });

  test('codex generated copy (packages/codex/.codex/skills/commands/ensemble-beads-build-wave/SKILL.md) does not contain the buggy phrase', () => {
    const contents = fs.readFileSync(CODEX_GENERATED_PATH, 'utf8');
    expect(contents).not.toMatch(BUGGY_TRIGGER_PHRASE);
  });

  test('opencode generated copy (fresh, generated into a throwaway temp dir) does not contain the buggy phrase', () => {
    const tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'pr7-beads-build-wave-opencode-'));
    try {
      fs.symlinkSync(path.join(REPO_ROOT, 'node_modules'), path.join(tmpRoot, 'node_modules'), 'dir');
      const outDir = path.join(tmpRoot, 'out');
      execFileSync(
        process.execPath,
        [
          path.join(REPO_ROOT, 'scripts', 'generate-opencode', 'index.js'),
          '--output-dir',
          outDir,
          '--packages-dir',
          path.join(REPO_ROOT, 'packages')
        ],
        { cwd: REPO_ROOT, encoding: 'utf8' }
      );

      const generatedPath = path.join(outDir, '.opencode', 'commands', 'ensemble', 'beads-build-wave.md');
      expect(fs.existsSync(generatedPath)).toBe(true);
      const contents = fs.readFileSync(generatedPath, 'utf8');
      expect(contents).not.toMatch(BUGGY_TRIGGER_PHRASE);
    } finally {
      fs.rmSync(path.join(tmpRoot, 'node_modules'), { force: true });
      fs.rmSync(tmpRoot, { recursive: true, force: true });
    }
  });

  describe('mutation proof: reverting the fix in a /tmp copy of the source reintroduces the phrase, and the real source still passes', () => {
    test('a /tmp copy with Step 2 reverted to the inverted condition is caught by the same assertion', () => {
      const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'pr7-beads-build-wave-mutant-'));
      try {
        const original = readSource();
        const needle = 'If the result is {ok:false} (UNAVAILABLE or any other error): run';
        expect(original).toContain(needle);
        const mutated = original.replace(
          needle,
          'If it is unavailable, errors, or returns zero tracks: run'
        );
        expect(mutated).not.toBe(original);

        const copyPath = path.join(tmpDir, 'beads-build-wave.yaml');
        fs.writeFileSync(copyPath, mutated, 'utf8');

        expect(fs.readFileSync(copyPath, 'utf8')).toMatch(BUGGY_TRIGGER_PHRASE);

        // Confirm again against the real, unmutated source: still clean.
        expect(readSource()).not.toMatch(BUGGY_TRIGGER_PHRASE);
      } finally {
        fs.rmSync(tmpDir, { recursive: true, force: true });
      }
    });
  });
});
