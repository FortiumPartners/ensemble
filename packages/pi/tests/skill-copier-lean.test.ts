/**
 * Lean skill shipping: Pi installs only what a skill's runtime needs.
 *
 * Part 1 drives copySkills over a temp source tree: SKILL.md always ships, files a shipped
 * file references (transitively) ship, scripts a skill invokes ship, authoring artifacts
 * nothing refers to do not, and a dangling reference never crashes the run.
 *
 * Part 2 is the copied-install smoke test: it generates the real repository into a temp
 * output root, copies that root to another temp dir with no repo around it (as an installed
 * package is), and checks that every file reference in the shipped markdown resolves there.
 */

import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { copySkills } from '../src/transformers/skill-copier';
import { generate } from '../src/generator';

const REPO_ROOT = path.resolve(__dirname, '..', '..', '..');

function tmp(prefix: string): string {
  return fs.mkdtempSync(path.join(os.tmpdir(), prefix));
}

function put(root: string, rel: string, content: string): void {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, 'utf-8');
}

function walk(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
}

describe('copySkills ships only what the skill runtime needs', () => {
  let src: string;
  let out: string;
  const SK = 'packages/demo/skills/thing';

  beforeEach(() => {
    src = tmp('pi-lean-src-');
    out = tmp('pi-lean-out-');
  });
  afterEach(() => {
    fs.rmSync(src, { recursive: true, force: true });
    fs.rmSync(out, { recursive: true, force: true });
  });

  const shipped = async (): Promise<string[]> => {
    await copySkills(src, out, {});
    return walk(path.join(out, 'skills', 'thing'))
      .map((f) => path.relative(path.join(out, 'skills', 'thing'), f).split(path.sep).join('/'))
      .sort();
  };

  it('does not copy unreferenced REFERENCE.md, examples, templates or authoring docs', async () => {
    put(src, `${SK}/SKILL.md`, '# Thing\n\nDo the thing.\n');
    put(src, `${SK}/REFERENCE.md`, '# Ref\n');
    put(src, `${SK}/README.md`, '# readme\n');
    put(src, `${SK}/VALIDATION.md`, '# validation\n');
    put(src, `${SK}/examples/a.example.ts`, 'export {};\n');
    put(src, `${SK}/templates/a.template.ts`, 'export {};\n');
    put(src, `${SK}/scripts/unused.js`, 'console.log(1);\n');

    expect(await shipped()).toEqual(['SKILL.md']);
  });

  it('copies a REFERENCE.md that SKILL.md links to, with the generated marker', async () => {
    put(src, `${SK}/SKILL.md`, '# Thing\n\nSee [reference](./REFERENCE.md#deep).\n');
    put(src, `${SK}/REFERENCE.md`, '# Ref\nuse ensemble:other\n');

    expect(await shipped()).toEqual(['REFERENCE.md', 'SKILL.md']);
    const ref = fs.readFileSync(path.join(out, 'skills', 'thing', 'REFERENCE.md'), 'utf-8');
    expect(ref).toContain('Generated by ensemble-pi generator');
    expect(ref).toContain('ensemble-other');
  });

  it('copies the references/ files that a SKILL.md names in a table, and those a phase file names in turn, not the files nothing names', async () => {
    put(
      src,
      `${SK}/SKILL.md`,
      [
        '# Thing',
        '',
        '| Phase | Instructions |',
        '|---|---|',
        '| 1. First | `references/phase-1-first.md` |',
        '| 2. Second | `references/phase-2-second.md` |',
        '',
      ].join('\n')
    );
    // A path from the skill root, and a bare file name that only resolves beside the file naming it
    put(src, `${SK}/references/phase-1-first.md`, '# Phase 1\n\nSee `references/deep/more.md`, then phase-3-third.md.\n');
    put(src, `${SK}/references/phase-2-second.md`, '# Phase 2\n');
    put(src, `${SK}/references/phase-3-third.md`, '# Phase 3\n');
    put(src, `${SK}/references/deep/more.md`, '# More\n');
    put(src, `${SK}/references/unnamed.md`, '# nothing names this\n');
    put(src, `${SK}/notes.txt`, 'stray\n');

    expect(await shipped()).toEqual([
      'SKILL.md',
      'references/deep/more.md',
      'references/phase-1-first.md',
      'references/phase-2-second.md',
      'references/phase-3-third.md',
    ]);
    for (const rel of ['references/phase-1-first.md', 'references/deep/more.md']) {
      const copy = fs.readFileSync(path.join(out, 'skills', 'thing', rel), 'utf-8');
      expect(copy.split('\n')[0]).toMatch(/^<!-- Generated by ensemble-pi generator /);
    }
  });

  it('copies a script named in SKILL.md (byte for byte, executable bit kept) and not its siblings', async () => {
    put(src, `${SK}/SKILL.md`, '# Thing\n\n```bash\nnode skills/thing/scripts/run.js --go\n```\n');
    put(src, `${SK}/scripts/run.js`, '#!/usr/bin/env node\r\nconsole.log("run");\n');
    fs.chmodSync(path.join(src, SK, 'scripts/run.js'), 0o755);
    put(src, `${SK}/scripts/other.js`, 'console.log("other");\n');

    expect(await shipped()).toEqual(['SKILL.md', 'scripts/run.js']);
    const copy = path.join(out, 'skills', 'thing', 'scripts', 'run.js');
    expect(fs.readFileSync(copy, 'utf-8')).toBe('#!/usr/bin/env node\r\nconsole.log("run");\n');
    expect(fs.statSync(copy).mode & 0o111).not.toBe(0);
  });

  it('resolves references transitively: markdown to markdown to script, and script to required module and data dir', async () => {
    put(src, `${SK}/SKILL.md`, '# Thing\n\nMore in `docs/deep.md`.\n');
    put(src, `${SK}/docs/deep.md`, 'Run `../scripts/main.js`.\n');
    put(
      src,
      `${SK}/scripts/main.js`,
      "const u = require('./util');\nconst dir = path.join(__dirname, 'patterns');\n"
    );
    put(src, `${SK}/scripts/util.js`, 'module.exports = {};\n');
    put(src, `${SK}/scripts/patterns/a.json`, '{}\n');
    put(src, `${SK}/scripts/unrelated.js`, '1;\n');

    expect(await shipped()).toEqual([
      'SKILL.md',
      'docs/deep.md',
      'scripts/main.js',
      'scripts/patterns/a.json',
      'scripts/util.js',
    ]);
  });

  it('never ships tests or node_modules, and never reaches outside the skill or into another skill', async () => {
    put(src, `${SK}/SKILL.md`, '# Thing\n\nSee `__tests__/t.test.js`, `../other/SKILL.md`, `../../secret.md`, `sub/SKILL.md`.\n');
    put(src, `${SK}/__tests__/t.test.js`, '1;\n');
    put(src, 'packages/demo/skills/other/SKILL.md', '# Other\n');
    put(src, 'packages/demo/skills/secret.md', 'x\n');
    put(src, `${SK}/sub/SKILL.md`, '# Nested\n');

    expect(await shipped()).toEqual(['SKILL.md']);
  });

  it('survives a missing referenced file, a URL, a cycle and a user-project file name', async () => {
    put(
      src,
      `${SK}/SKILL.md`,
      '# Thing\n\nSee `GONE.md`, [x](https://example.com/a.md), `package.json`, [cycle](./REFERENCE.md).\n'
    );
    put(src, `${SK}/REFERENCE.md`, 'Back to [skill](./SKILL.md).\n');

    expect(await shipped()).toEqual(['REFERENCE.md', 'SKILL.md']);
  });

  it('ships the same set on a dry run without writing', async () => {
    put(src, `${SK}/SKILL.md`, '# Thing\n\nSee REFERENCE.md.\n');
    put(src, `${SK}/REFERENCE.md`, '# Ref\n');
    const results = await copySkills(src, out, { dryRun: true });
    expect(results.map((r) => path.basename(r.outputPath)).sort()).toEqual(['REFERENCE.md', 'SKILL.md']);
    expect(fs.existsSync(path.join(out, 'skills'))).toBe(false);
  });
});

describe('copied-install smoke test (real repository, no repo around the copy)', () => {
  let generated: string;
  let installed: string;

  beforeAll(async () => {
    generated = tmp('pi-smoke-gen-');
    installed = path.join(tmp('pi-smoke-install-'), 'ensemble-pi');
    await generate({ sourceRoot: REPO_ROOT, outputRoot: generated, dryRun: false, verbose: false, validate: false });
    fs.cpSync(generated, installed, { recursive: true });
  }, 120000);

  afterAll(() => {
    fs.rmSync(generated, { recursive: true, force: true });
    fs.rmSync(path.dirname(installed), { recursive: true, force: true });
  });

  it('ships skills, and every shipped skill has its SKILL.md', () => {
    const skillsDir = path.join(installed, 'skills');
    const dirs = fs.readdirSync(skillsDir, { withFileTypes: true }).filter((e) => e.isDirectory());
    expect(dirs.length).toBeGreaterThan(10);
    for (const d of dirs) {
      expect(fs.existsSync(path.join(skillsDir, d.name, 'SKILL.md'))).toBe(true);
    }
  });

  it('resolves every relative markdown link in shipped markdown inside the copy', () => {
    const dangling: string[] = [];
    for (const file of walk(installed).filter((f) => f.endsWith('.md'))) {
      const text = fs.readFileSync(file, 'utf-8');
      for (const m of text.matchAll(/\]\(([^)\s]+)\)/g)) {
        const target = m[1].replace(/#.*$/, '');
        // Directory links (`templates/`) name no file; quotes mean it is code, not a link.
        if (!target || target.endsWith('/') || /["'@]/.test(target)) continue;
        if (/^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith('/')) continue;
        const resolved = path.resolve(path.dirname(file), target);
        if (!resolved.startsWith(installed + path.sep) || !fs.existsSync(resolved)) {
          dangling.push(`${path.relative(installed, file)} -> ${m[1]}`);
        }
      }
    }
    expect(dangling).toEqual([]);
  });

  it('resolves every skills/<skill>/<file> path named in shipped markdown to a file in the copy', () => {
    const skillDirs = new Set(
      fs.readdirSync(path.join(installed, 'skills'), { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name)
    );
    const dangling: string[] = [];
    for (const file of walk(installed).filter((f) => f.endsWith('.md'))) {
      const text = fs.readFileSync(file, 'utf-8');
      for (const m of text.matchAll(/skills\/([a-z0-9-]+)\/([A-Za-z0-9_@./-]*[A-Za-z0-9_@-]\.[A-Za-z][A-Za-z0-9]{0,5})(?![\w/])/g)) {
        if (!skillDirs.has(m[1]) && !fs.existsSync(path.join(REPO_ROOT, 'packages', 'pi', 'skills', m[1]))) continue;
        if (!fs.existsSync(path.join(installed, 'skills', m[1], m[2]))) {
          dangling.push(`${path.relative(installed, file)} -> ${m[0]}`);
        }
      }
    }
    expect(dangling).toEqual([]);
  });

  it('ships every script and file that a source skill names, as a source-side closure check', () => {
    // For each skill in the copy, every .js/.sh/.py/.json/.md the source SKILL.md mentions by
    // its exact relative path (when it exists in the source skill dir) must be in the copy.
    const missing: string[] = [];
    const skillsDir = path.join(installed, 'skills');
    for (const pkg of fs.readdirSync(path.join(REPO_ROOT, 'packages'))) {
      const base = path.join(REPO_ROOT, 'packages', pkg, 'skills');
      if (!fs.existsSync(base) || pkg === 'pi' || pkg === 'full' || pkg === 'assessment') continue;
      for (const name of fs.readdirSync(base)) {
        const skillMd = path.join(base, name, 'SKILL.md');
        if (!fs.existsSync(skillMd) || !fs.existsSync(path.join(skillsDir, name))) continue;
        const text = fs.readFileSync(skillMd, 'utf-8');
        for (const m of text.matchAll(/(?:scripts|templates|patterns|references)\/[A-Za-z0-9_.-]+\.[a-z]{1,5}/g)) {
          if (fs.existsSync(path.join(base, name, m[0])) && !fs.existsSync(path.join(skillsDir, name, m[0]))) {
            missing.push(`${name}: ${m[0]}`);
          }
        }
      }
    }
    expect(missing).toEqual([]);
  });
});
